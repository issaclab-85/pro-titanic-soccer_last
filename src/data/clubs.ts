const LEGACY_HAIR_MAP: Record<string, HairStyleId> = {
  fade: 'ronaldo',
  crop: 'bellingham',
  braids: 'gullit',
  buzz: 'kante',
  curl: 'cucurella',
  sweep: 'grealish',
  headband: 'haaland',
};

const VALID_HAIR_SET = new Set<string>(HAIR_STYLES.map((h) => h.id));

export function normalizeHairStyle(raw: unknown): HairStyleId {
  const key = String(raw ?? '').trim().toLowerCase();
  if (VALID_HAIR_SET.has(key)) return key as HairStyleId;
  if (key in LEGACY_HAIR_MAP) return LEGACY_HAIR_MAP[key];
  return 'ronaldo';
}

